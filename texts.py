def _plural(n, one, few, many):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return one
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return few
    return many


_CASC_WORDS = {1: "один из них — каскад", 2: "два из них — каскады", 3: "три из них — каскады"}


def rules(part: str, n_el: int, n_cas: int) -> str:
    el = _plural(n_el, "прыжковый элемент", "прыжковых элемента", "прыжковых элементов")
    cas = _CASC_WORDS.get(n_cas, f"каскадов — до {n_cas}")
    return f"📋 По правилам в {part}: {n_el} {el}, {cas}."


