from scoring import TOLERANCE


def _plural(n, one, few, many):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return one
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return few
    return many


def _n(x) -> str:
    return str(int(x)) if float(x) == int(x) else str(x)


def _place_rules() -> str:
    """Очки за место: числа берутся из scoring.TOLERANCE, чтобы текст не расходился с подсчётом."""
    a, b, c = TOLERANCE["place"]
    pl = lambda n: f"±{_n(n)} {_plural(int(n), 'место', 'места', 'мест')}"  # noqa: E731
    return (
        ("1 — угадано точно,\n" if a == 0 else f"1 — отклонение {pl(a)},\n")
        + f"0.75 — отклонение {pl(b)},\n"
        + f"0.5 — отклонение {pl(c)},\n"
        + "0.25 — мимо (отклонение больше),\n"
        + "0 — пункт пропущен.\n\n"
    )


def _points_rules() -> str:
    def row(label, key):
        a, b, c = TOLERANCE[key]
        pt = lambda n: f"±{_n(n)} {_plural(int(n) if float(n) == int(n) else 2, 'балл', 'балла', 'баллов')}"  # noqa: E731
        return f"<b>{label}</b>: {pt(a)} — 1, {pt(b)} — 0.75, {pt(c)} — 0.5, больше — 0.25.\n"
    return (
        "• <b>баллы</b> за КП, ПП и в сумме: от 0 до 1. Чем ближе к реальным, тем больше очков.\n\n"
        + row("КП", "sp") + row("ПП", "fs") + row("Сумма", "total")
        + "Пропущенный пункт — 0.\n\n"
    )


_PLACE_RULES = "• <b>место</b>: от 0 до 1.\n\n" + _place_rules()
_POINTS_RULES = _points_rules()

